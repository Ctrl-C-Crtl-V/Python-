
#Entrada de Dados

Base=float(input('Digite a Base do seu Quadrado: '))
Altura=float(input('Digite a Altura do seu Quadrado: '))

#processamento
Area=(Base * Altura)
Perimetro=(Base + Altura + Base + Altura)


#Saída de Dados
print('--------------------------------------------------------------------')
print ('Blz, sua Área é: {}\nE seu Perimetro: {}' .format (Area, Perimetro))
print('--------------------------------------------------------------------')
